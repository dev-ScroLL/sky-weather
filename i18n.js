const messages = Object.fromEntries(Object.entries(languages).map(([language, values]) => [
  language, Object.fromEntries(messageKeys.map((key, index) => [key, values[index]]))
]));
let locale = initialLanguage();

function initialLanguage() {
  try {
    const saved = localStorage.getItem('sky-language');
    if (Object.hasOwn(messages, saved)) return saved;
  } catch {
    // Storage may be disabled or unavailable for local files.
  }
  const preferences = [...(navigator.languages ?? []), navigator.language];
  return preferences.map((tag) => tag?.toLowerCase().split('-')[0]).find((code) => Object.hasOwn(messages, code)) ?? 'en';
}

function t(key, values = {}) {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '');
}

function applyLanguage() {
  document.documentElement.lang = locale;
  document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
  document.title = 'Sky. · ' + t('title');
  document.querySelector('meta[name="description"]').content = t('description');
  document.querySelectorAll('[data-text]').forEach((el) => { el.textContent = t(el.dataset.text); });
  document.querySelectorAll('[data-label]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.label)));
  document.getElementById('query').placeholder = t('search');
  document.getElementById('language').value = locale;
}

function localNumber(value, options) {
  return new Intl.NumberFormat(locale, options).format(value);
}
